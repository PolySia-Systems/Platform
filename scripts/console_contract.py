"""Generate checked TypeScript from the sole Python Console wire contract."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
from polysia.monitoring.console_contract import CONTRACT_MODELS  # noqa: E402


def ts(schema: dict[str, Any]) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[1]
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(item) for item in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(item) for item in schema["anyOf"])
    kind = schema.get("type")
    if kind == "object":
        fields = []
        for name, value in schema.get("properties", {}).items():
            optional = "" if name in schema.get("required", []) else "?"
            fields.append(f"{name}{optional}: {ts(value)}")
        return "{ " + "; ".join(fields) + " }"
    if kind == "array":
        return f"({ts(schema['items'])})[]"
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }[kind]


def generate() -> str:
    schemas = {model.__name__: model.model_json_schema() for model in CONTRACT_MODELS}
    definitions: dict[str, Any] = {}
    for name, schema in schemas.items():
        definitions.update(schema.get("$defs", {}))
        definitions[name] = schema
    lines = ["// Generated by scripts/console_contract.py. Edit the Python contract."]
    for name, schema in sorted(definitions.items()):
        lines.append(f"export type {name} = {ts(schema)};")
    lines.append(
        "export const schemas = " + json.dumps(schemas, sort_keys=True, indent=2) + " as const;"
    )
    return "\n".join(lines) + "\n"


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = Path(__file__).resolve().parents[1] / "frontend/src/contract.generated.ts"
    expected = generate()
    if args.check:
        if not target.is_file() or target.read_text(encoding="utf-8") != expected:
            raise SystemExit(
                "Console TypeScript mapping is stale; run python scripts/console_contract.py"
            )
    else:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected, encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
